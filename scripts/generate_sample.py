def r_amount(lo, hi):
    if lo == hi: return float(lo)
    import math
    # 对数正态: 中位数接近下限, 长尾偶尔出现大额(95 分位 ~ hi 的一半)
    sigma = math.log(hi / lo) / 2.2
    v = lo * math.exp(random.normalvariate(0, sigma))
    return round(min(v, hi), 2)

def r_time(day):
    return f"{day.isoformat()} {random.randint(7,23):02d}:{random.randint(0,59):02d}:{random.randint(0,59):02d}"

